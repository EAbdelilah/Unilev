require("dotenv").config();
const os = require("os");
const path = require("path");
const fs = require("fs");
const { ethers } = require("ethers");
const RPC = process.env.BASE_RPC_URL || "https://mainnet.base.org";
const USDC = ethers.getAddress("0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913");
const WETH = ethers.getAddress("0x4200000000000000000000000000000000000006");
const ROUTER = ethers.getAddress(process.env.V4_ROUTER_ADDRESS || "0x57E75A87A62ab8Ff14C59FA10Ac2AB2c8cBD45D1");
const HOOK = ethers.getAddress(process.env.V4_HOOK_ADDRESS || "0x6f98Ea19e522Ecc706E0Fb1574BDA8D32aC510C8");
const HOOK_KEY = [WETH, USDC, 3000, 60, HOOK];
const ADAPTER = "0x9Ee7A81D90fF816Aa9Ae0C9C8dDFAE85E11F5983";
const idOf = (k) => ethers.keccak256(ethers.AbiCoder.defaultAbiCoder().encode(["address","address","uint24","int24","address"], k));
(async () => {
    const p = new ethers.JsonRpcProvider(RPC);
    const deployer = new ethers.Wallet(process.env.PRIVATE_KEY, p);
    const tiny = process.env.TINY_TRADER_PK ? new ethers.Wallet(process.env.TINY_TRADER_PK, p) : deployer;
    const t2 = JSON.parse(fs.readFileSync(path.join(os.tmpdir(), "eswap-ext-trader2.json"), "utf8"));
    const s  = JSON.parse(fs.readFileSync(path.join(os.tmpdir(), "eswap-ext-solver.json"), "utf8"));
    const usdc = new ethers.Contract(USDC, ["function balanceOf(address) view returns (uint256)","function allowance(address,address) view returns (uint256)"], p);
    const router = new ethers.Contract(ROUTER, ["function erc20BorrowEscrow(address,address) view returns (uint256)","function registeredSolvers(address) view returns (bool)","function executorWhitelist(address) view returns (bool)"], p);
    const hook = new ethers.Contract(HOOK, ["function positions(bytes32,address) view returns (address,uint256,uint256,uint8,bool,uint160,int24,int24,uint128)"], p);
    const hid = idOf(HOOK_KEY);
    const wei = (x) => ethers.formatEther(x);
    console.log("deployer", deployer.address, "ETH", wei(await p.getBalance(deployer.address)), "USDC", (await usdc.balanceOf(deployer.address)).toString());
    console.log("tiny    ", tiny.address, "ETH", wei(await p.getBalance(tiny.address)));
    console.log("trader2 ", t2.address, "ETH", wei(await p.getBalance(t2.address)), "USDC", (await usdc.balanceOf(t2.address)).toString(), "allow", (await usdc.allowance(t2.address, ROUTER)).toString());
    console.log("solver  ", s.address, "ETH", wei(await p.getBalance(s.address)), "USDC", (await usdc.balanceOf(s.address)).toString(), "allow", (await usdc.allowance(s.address, ROUTER)).toString());
    console.log("solver escrow USDC", (await router.erc20BorrowEscrow(s.address, USDC)).toString(), "whitelisted", await router.registeredSolvers(s.address));
    console.log("adapter executorWhitelist", await router.executorWhitelist(ADAPTER));
    const pos = await hook.positions(hid, t2.address);
    console.log("trader2 position.trader", pos[0], "collateral", pos[1].toString());
})().catch(e => { console.error(e); process.exit(1); });
